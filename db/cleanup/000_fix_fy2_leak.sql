-- 修正SQL（ADR-045追補 / 2026-07-20）
-- FY-2日次タブの末尾に残っていたFY範囲外（2026-04以降）の入力残骸が
-- FY-3タブと二重取込されていたため削除する。
-- 対象: 2026-04 ¥241,916 / 2026-05 ¥35,320 / 2026-07 ¥30,000 / 2026-08 ¥176,460
-- （シート自身の月次集計にも含まれていない行＝削除してもシートと一致する）
BEGIN;
DELETE FROM transactions
WHERE user_id = 1
  AND client_key LIKE 'imp:d2:%'
  AND accrual_date >= '2026-04-01';
COMMIT;
